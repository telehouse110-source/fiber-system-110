export function getFiberColor(coreNumber: number, customColors?: FiberColorConfig[]): FiberColorConfig {
  const colors = customColors && customColors.length > 0 ? customColors : STANDARD_FIBER_COLORS;
  const index = ((coreNumber - 1) % colors.length);
  return colors[index];
}

// Generate cores for a cable
export function generateCoresForCable(cableId: string, coreCount: number, customColors?: FiberColorConfig[]) {
  const cores = [];
  for (let i = 1; i <= coreCount; i++) {
    const col = getFiberColor(i, customColors);
    const tubeNumber = Math.ceil(i / 12);
    const tubeColor = getFiberColor(tubeNumber, customColors).name;
    cores.push({
      id: `${cableId}-C${i.toString().padStart(2, '0')}`,
      cableId,
      coreNumber: i,
      tubeNumber,
      tubeColor,
      colorName: col.name,
      colorHex: col.hex,
      status: 'Spare' as const,
      signalPowerDbm: undefined,
      attenuationLossDb: 0.35,
      startPoint: 'Origin',
      endPoint: 'Terminal',
      connectedToType: 'NONE' as const,
      connectedToId: undefined,
      connectedToLabel: undefined,
      notes: `Tube ${tubeNumber} (${tubeColor}) - Core ${i} (${col.name})`,
      lastTestedDate: '2026-09-01',
    });
  }
  return cores;
}

